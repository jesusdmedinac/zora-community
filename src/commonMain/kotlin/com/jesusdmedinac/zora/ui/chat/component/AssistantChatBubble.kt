/**
 * AI Assistant chat message content.
 * Conforms 100% to the containerless specification in design/zora-community.pen:
 * rendered directly over $canvas without gray container boxes or borders.
 * Optionally renders dynamic SDUI templates generated by the copilot via json-to-compose.
 */
@Composable
fun AssistantChatBubble(
    text: String,
    modifier: Modifier = Modifier,
    dynamicDocument: ComposeDocument? = null,
    onCustomAction: ((ComposeAction.Custom) -> Unit)? = null,
) {
    val platform = ZoraTheme.platform
    val fontSize = when (platform) {
        ZoraPlatformVariant.HUMAN_INTERFACE -> 15.sp
        ZoraPlatformVariant.MATERIAL3 -> 15.sp
    }

    Column(
        modifier = modifier
            .fillMaxWidth()
            .padding(vertical = 2.dp),
        verticalArrangement = Arrangement.spacedBy(8.dp),
    ) {
        Text(
            text = text,
            fontFamily = ZoraTokens.FontBody,
            fontSize = fontSize,
            lineHeight = 22.sp,
            color = ZoraTokens.OnSurface,
        )

        if (dynamicDocument != null) {
            val customHandlers = buildMap<String, (ComposeAction.Custom) -> Unit> {
                if (onCustomAction != null) {
                    put(ZoraSduiTemplates.ACTION_OPEN_PAYWALL, onCustomAction)
                    put(ZoraSduiTemplates.ACTION_CONFIRM_MEMORY, onCustomAction)
                    put(ZoraSduiTemplates.ACTION_DISMISS_MEMORY, onCustomAction)
                }
            }

            CompositionLocalProvider(
                LocalCustomActionHandlers provides customHandlers,
            ) {
                dynamicDocument.ToCompose()
            }
        }
    }
}

